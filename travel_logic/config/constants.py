# ─── 베이지안 평균 점수 계산 상수 ──────────────────────────────
# 리뷰 수와 평점을 하나의 공식으로 복합 계산 (단순 rating×15 대체).
#
# 공식:
#   bayesian_rating = (C × global_avg + review_count × rating) / (C + review_count)
#   base_score      = bayesian_rating × BAYESIAN_SCORE_MULTIPLIER
#
# 핵심 원리:
#   리뷰가 적으면 → 글로벌 평균(3.5)에 수렴 (리뷰 없는 장소의 과대평가 방지)
#   리뷰가 많으면 → 실제 평점에 수렴 (신뢰도가 높으므로 그대로 반영)
#
# 예시 비교:
#   평점 5.0, 리뷰  2개 → (50×3.5 + 2×5.0)/52  = 3.65점 → ×15 = 54.8점
#   평점 5.0, 리뷰200개 → (50×3.5 + 200×5.0)/250 = 4.70점 → ×15 = 70.5점
#   평점 4.0, 리뷰500개 → (50×3.5 + 500×4.0)/550 = 3.95점 → ×15 = 59.3점
BAYESIAN_C                = 50    # 기준 리뷰 수 (이보다 적으면 글로벌 평균으로 할인)
